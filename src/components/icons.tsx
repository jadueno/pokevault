/** Iconos de trazo fino compartidos para botones de acción (refrescar, editar, copiar…),
 * mismo lenguaje visual que ya usan los iconos de navegación de App.tsx (líneas finas,
 * sin relleno, heredan el color vía currentColor) — un emoji de color fijo (🔄/✏️/📋) no
 * puede adoptar el color del botón que lo contiene (texto muted, blanco sobre una tarjeta
 * oscura, etc.), así que siempre desentona con la paleta de la app. */
type IconProps = { className?: string };

function Svg({ className, children }: { className?: string; children: React.ReactNode }) {
  return (
    <svg
      aria-hidden="true"
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth="2"
      strokeLinecap="round"
      strokeLinejoin="round"
      className={className}
    >
      {children}
    </svg>
  );
}

export function RefreshIcon({ className }: IconProps) {
  return (
    <Svg className={className}>
      <path d="M21 12a9 9 0 1 1-2.64-6.36" />
      <polyline points="21 3 21 9 15 9" />
    </Svg>
  );
}

